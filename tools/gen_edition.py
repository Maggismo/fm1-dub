"""MEDEKAT edition: a fingerprint of the eight recipes (amb.c's PIECES), as firmware/src/app/edition.h.
app.h folds it into PROJ_FORMAT, so a build with other recipes reads a project saved by the one before as a
format it does not know, and starts every piece from the new recipes once; the same recipes keep your changes.
  tools/gen_edition.py > firmware/src/app/edition.h"""
import re
from pathlib import Path
src = (Path(__file__).resolve().parent.parent / "firmware/src/dsp/amb.c").read_text()
m = re.search(r'PIECES\[EN_NPIECES\]\s*=\s*\{(.*?)\n\};', src, re.S)
body = re.sub(r"\s+", "", m.group(1))
h = 2166136261
for b in body.encode():
    h = ((h ^ b) * 16777619) & 0xFFFFFFFF
ed = (h ^ (h >> 16)) & 0xFFFF
print("/* generated by tools/gen_edition.py: a fingerprint of the eight recipes (see app.h). Do not edit */")
print("#define EN_EDITION 0x%04Xu" % ed)
